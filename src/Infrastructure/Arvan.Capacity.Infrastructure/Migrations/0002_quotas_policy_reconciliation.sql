-- Quotas, fairness policy, admin-chosen pool ids, quota-scoped ledger adjustments, reconciliation reports.

ALTER TABLE pools ALTER COLUMN id SET GENERATED BY DEFAULT;

ALTER TABLE products
    ADD COLUMN max_active_holds    smallint NOT NULL DEFAULT 20,
    ADD COLUMN max_waiting         smallint NOT NULL DEFAULT 4,
    ADD COLUMN max_pool_share_pct  smallint NOT NULL DEFAULT 100 CHECK (max_pool_share_pct BETWEEN 1 AND 100);

-- The limit is deliberately not a CHECK: a contract may shrink below current usage, and then new
-- holds fail until usage drops under it. It is a condition of the hold UPDATE instead.
CREATE TABLE quotas (
    customer_id    text   NOT NULL,
    resource_class text   NOT NULL,
    region         text   NOT NULL,
    quota_limit    bigint NOT NULL CHECK (quota_limit >= 0),
    held           bigint NOT NULL DEFAULT 0,
    used           bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (customer_id, resource_class, region),
    CHECK (held >= 0 AND used >= 0)
);

-- A quota adjustment has a customer but no pool.
ALTER TABLE ledger_entries ALTER COLUMN pool_id DROP NOT NULL;
ALTER TABLE ledger_entries ADD CONSTRAINT ledger_pool_unless_adjust CHECK (pool_id IS NOT NULL OR entry_type = 'ADJUST');
CREATE INDEX ledger_entries_quota ON ledger_entries (customer_id, resource_class, region) WHERE customer_id IS NOT NULL;

CREATE INDEX reservations_cooldown ON reservations (customer_id, product_code, updated_at) WHERE stored_status = 'EXPIRED';
CREATE INDEX reservations_open_per_customer ON reservations (customer_id, product_code) WHERE stored_status IN ('HELD', 'WAITING');

CREATE TABLE reconciliation_reports (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at         timestamptz NOT NULL,
    drift_rows int         NOT NULL,
    report     jsonb       NOT NULL
);
